import type { OtherDocument } from "./scopeDocuments";

const LINES_PER_PAGE = 10;

function document(file: string, lines: readonly string[]): OtherDocument {
  const pages: { chineseLines: readonly string[] }[] = [];
  for (let at = 0; at < lines.length; at += LINES_PER_PAGE) {
    pages.push({ chineseLines: lines.slice(at, at + LINES_PER_PAGE) });
  }
  return { file, pages };
}

interface ContractTerms {
  company: string;
  employee: string;
  role: string;
  start: string;
  manager: string;
  salary: string;
  hours: string;
  lunch: string;
  home: string;
  callIn: string;
  holiday: string;
  probation: string;
  probationNotice: string;
  notice: string;
}

function contract(file: string, terms: ContractTerms): OtherDocument {
  return document(file, [
    "劳动合同书",
    `甲方（用人单位）：${terms.company}`,
    `乙方（劳动者）：${terms.employee}`,
    `第一条　工作岗位：乙方担任${terms.role}，自${terms.start}起入职，向${terms.manager}汇报。`,
    `第二条　劳动报酬：乙方月工资为人民币${terms.salary}，于每月最后一个工作日发放。`,
    `第三条　工作时间和地点：工作时间为周一至周五${terms.hours}，午休${terms.lunch}。`,
    `乙方${terms.home}，须事先与主管商定。`,
    `甲方可提前${terms.callIn}小时通知乙方在居家工作日到岗。`,
    `第四条　带薪年休假：乙方每年享有带薪年休假${terms.holiday}天，法定节假日另计。`,
    `第五条　试用期：试用期为${terms.probation}。试用期内任何一方提前${terms.probationNotice}书面通知对方，可以解除本合同。`,
    `第六条　解除合同：试用期满后，任何一方须提前${terms.notice}书面通知对方，方可解除本合同。`,
    "第七条　社会保险：甲方依法为乙方缴纳社会保险和住房公积金。",
    "第八条　保密：乙方在职期间及离职后均须对甲方的商业秘密保密。",
    "第九条　适用法律：本合同适用中华人民共和国法律。",
    "甲方（盖章）：　　　　　　　　乙方（签字）：",
    "签订日期：　　　　年　　月　　日",
  ]);
}

