import type { PdfPage } from "../../tests/helpers/pdf";

export interface OtherDocument {
  file: string;
  pages: readonly PdfPage[];
}

const LINES_PER_PAGE = 15;

function document(file: string, lines: readonly string[]): OtherDocument {
  const pages: PdfPage[] = [];
  for (let at = 0; at < lines.length; at += LINES_PER_PAGE) {
    pages.push({ lines: lines.slice(at, at + LINES_PER_PAGE) });
  }
  return { file, pages };
}

interface AgreementTerms {
  company: string;
  employee: string;
  role: string;
  start: string;
  manager: string;
  salary: string;
  hours: string;
  lunch: string;
  home: string;
  callIn: string;
  holiday: string;
  carried: string;
  carriedBy: string;
  probation: string;
  probationNotice: string;
  notice: string;
  employer: string;
  employeeShare: string;
  law: string;
}

function agreement(file: string, terms: AgreementTerms): OtherDocument {
  return document(file, [
    "EMPLOYMENT AGREEMENT",
    `This Employment Agreement is made between ${terms.company} (the Company) and ${terms.employee} (the Employee).`,
    "1. Role and start date",
    `The Employee is employed as ${terms.role} and starts on ${terms.start}.`,
    `The Employee reports to the ${terms.manager}.`,
    "2. Pay",
    `The salary is ${terms.salary} per year, paid monthly in arrears on the last working day of the month.`,
    "3. Hours and place of work",
    `Normal hours are ${terms.hours}, Monday to Friday, with a ${terms.lunch} unpaid lunch break.`,
    `The Employee may work from home ${terms.home}, agreed in advance with the manager.`,
    `The Company may ask the Employee to attend the office on a working-from-home day with ${terms.callIn} hours' notice.`,
    "4. Holiday",
    `The Employee is entitled to ${terms.holiday} working days of paid holiday per year, in addition to public holidays.`,
    `Up to ${terms.carried} unused days may be carried over into the next year and must be taken by ${terms.carriedBy}.`,
    "5. Probation",
    `The first ${terms.probation} are a probation period. During probation either side may end this agreement`,
    `by giving ${terms.probationNotice} written notice.`,
    "6. Notice",
    `After probation, either side must give ${terms.notice} written notice to end this agreement.`,
    "The Company may pay salary in lieu of notice instead of requiring the Employee to work the notice period.",
    "7. Pension",
    `The Company will enrol the Employee in its workplace pension scheme and contribute ${terms.employer} percent of salary.`,
    `The Employee contributes ${terms.employeeShare} percent of salary through payroll.`,
    "8. Confidentiality",
    "The Employee must keep the Company's confidential information secret during and after employment.",
    "9. Governing law",
    `This agreement is governed by the laws of ${terms.law}.`,
    "Signed for the Company: ____________________  Date: ____________",
    "Signed by the Employee: ____________________  Date: ____________",
  ]);
}

