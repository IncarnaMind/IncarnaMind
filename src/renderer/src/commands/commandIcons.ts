export function commandIcon(command: Command): CommandIcon | undefined {
  return command.icon ?? ICONS[command.id];
}

/**
 * Whether its menu item is red, last, with a red icon (DESIGN.md, Menus): what deletes or removes.
 * Closing a tab is in the danger group, to stay last, but Reopen closed tab takes it back, so it
 * stays in ink.
 */
export const isDestructive = (command: Command): boolean =>
  command.group === "danger" && !command.id.startsWith("tab.close");
